#!/usr/bin/env node
/**
 * generate-seed-sql.js
 *
 * Reads data/survey-data.ts and generates INSERT statements for:
 *   - survey (1 row)
 *   - survey_question (61 rows with frontend_qid)
 *   - answer_option (for single/multiple choice questions)
 *   - survey_question_mapping (61 rows)
 *
 * Usage: node scripts/generate-seed-sql.js > supabase/migrations/20260307100001_seed_survey_data.sql
 */

const fs = require("fs");
const path = require("path");

const srcPath = path.join(__dirname, "..", "data", "survey-data.ts");
const src = fs.readFileSync(srcPath, "utf-8");

// ---------------------------------------------------------------------------
// Parse the surveyQuestions array from the TypeScript source
// ---------------------------------------------------------------------------

// Extract the array body between `surveyQuestions: SurveyQuestion[] = [` and `];`
const arrMatch = src.match(
  /export\s+const\s+surveyQuestions\s*:\s*SurveyQuestion\[\]\s*=\s*\[([\s\S]*?)\n\];/
);
if (!arrMatch) {
  console.error("Could not find surveyQuestions array in survey-data.ts");
  process.exit(1);
}

// Eval-safe: the array body is plain JS literals (strings, numbers, booleans, arrays).
// We wrap it in brackets and use Function() so we don't need a TS compiler.
const arrayBody = arrMatch[1];
// Replace trailing commas before ] or } to make it valid JSON-ish for Function()
const questions = new Function(`return [${arrayBody}]`)();

// ---------------------------------------------------------------------------
// SQL helpers
// ---------------------------------------------------------------------------

function esc(str) {
  if (str == null) return "NULL";
  return "'" + String(str).replace(/'/g, "''") + "'";
}

// ---------------------------------------------------------------------------
// Generate SQL
// ---------------------------------------------------------------------------

const lines = [];

lines.push("-- Auto-generated by scripts/generate-seed-sql.js — do not edit manually");
lines.push(
  "-- Run: node scripts/generate-seed-sql.js > supabase/migrations/20260307100001_seed_survey_data.sql"
);
lines.push("");
lines.push("BEGIN;");
lines.push("");

// 1. Insert the survey
lines.push("-- ─── Survey ─────────────────────────────────────────────────────────────────");
lines.push(`INSERT INTO survey (title, description, language, estimated_duration_min, status)`);
lines.push(
  `VALUES ('LoveIQ Survey', 'The LoveIQ personal sexuality & relationship survey', 'en', 20, 'active');`
);
lines.push("");

// We'll reference survey id via a variable
lines.push("-- Capture the survey id");
lines.push("DO $$");
lines.push("DECLARE");
lines.push("  v_survey_id BIGINT;");
lines.push("  v_q_id BIGINT;");
lines.push("BEGIN");
lines.push(
  "  SELECT id INTO v_survey_id FROM survey WHERE title = 'LoveIQ Survey' AND status = 'active' LIMIT 1;"
);
lines.push("");

// 2. Insert questions + answer options + mappings
lines.push("  -- ─── Questions, Options & Mappings ──────────────────────────────────────────");

for (let i = 0; i < questions.length; i++) {
  const q = questions[i];
  const qType = q.answerType; // open, scale, single, multiple
  const displayOrder = i + 1;

  lines.push("");
  lines.push(`  -- Q${displayOrder}: ${q.qId} (${qType})`);
  lines.push(
    `  INSERT INTO survey_question (type, question, subinfo, display_order, required, frontend_qid, status)`
  );
  lines.push(
    `  VALUES (${esc(qType)}, ${esc(q.question)}, ${esc(q.guide)}, ${displayOrder}, ${q.required}, ${esc(q.qId)}, 'active')`
  );
  lines.push(`  RETURNING id INTO v_q_id;`);

  // Insert answer options for single/multiple choice questions
  if ((qType === "single" || qType === "multiple") && q.options && q.options.length > 0) {
    for (let j = 0; j < q.options.length; j++) {
      const optText = q.options[j];
      lines.push(
        `  INSERT INTO answer_option (survey_question_id, option_text, option_value, display_order)`
      );
      lines.push(`  VALUES (v_q_id, ${esc(optText)}, ${esc(optText)}, ${j + 1});`);
    }
  }

  // Insert mapping
  lines.push(
    `  INSERT INTO survey_question_mapping (survey_id, question_id) VALUES (v_survey_id, v_q_id);`
  );
}

lines.push("");
lines.push("END $$;");
lines.push("");
lines.push("COMMIT;");

// ---------------------------------------------------------------------------
// Output
// ---------------------------------------------------------------------------

process.stdout.write(lines.join("\n") + "\n");
