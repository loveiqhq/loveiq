#!/usr/bin/env node
// Converts 14 per-archetype DOCX summary files → data/report-summary.ts
// Run: node scripts/convert-summary-docx.js
// Source: the per-archetype "Summaries 2-Page" DOCX exports

import mammoth from "mammoth";
import { readdir, writeFile } from "fs/promises";
import { join, basename } from "path";
import { fileURLToPath } from "url";
import { dirname } from "path";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const SOURCE_DIR = join(__dirname, "../.source-artifacts/report-content-v3/by-archetype");
const OUT_FILE = join(__dirname, "../data/report-summary.ts");

// Maps DOCX filename stem → archetype name used throughout the codebase.
// V9 renames are reflected in both filename stems and display names.
const FILENAME_TO_ARCHETYPE = {
  "01_Sensual_Connector": "Sensual Connector",
  "02_Spark_Seeker": "Spark Seeker",
  "03_Relational_Nurturer": "Relational Nurturer",
  "04_Radiant_Performer": "Radiant Performer",
  "05_Explorer_of_Edges": "Explorer of Edges",
  "06_Curious_Apprentice": "Curious Apprentice",
  "07_Spiritual_Lover": "Spiritual Lover",
  "08_Minimalist_Companion": "Minimalist Companion",
  "09_Emotional_Voyeur": "Emotional Voyeur",
  "10_Authority_Conductor": "Authority Conductor",
  "11_Loyal_Ritualist": "Loyal Ritualist",
  "12_Tender_Devotee": "Tender Devotee",
  "13_Analytical_Sexualist": "Analytical Sexualist",
  "14_Quiet_Withdrawer": "Quiet Withdrawer",
};

function cleanHtml(html) {
  return (
    html
      // Remove any H1 title tag
      .replace(/<h1[^>]*>[\s\S]*?<\/h1>/gi, "")
      // Remove leading title paragraph that appears before the first H3
      // (mammoth renders the DOCX "Title" style as a plain <p> when unrecognised)
      .replace(/^(<p>[^<]*<\/p>\s*)+(?=<h3)/i, "")
      // Remove empty paragraphs mammoth sometimes emits
      .replace(/<p>\s*<\/p>/g, "")
      // Normalize whitespace between tags
      .replace(/>\s{2,}</g, "> ")
      .replace(/\s{2,}</g, " <")
      .trim()
  );
}

async function main() {
  const files = (await readdir(SOURCE_DIR)).filter((f) => f.endsWith(".docx")).sort();

  const entries = [];

  for (const file of files) {
    const stem = basename(file, ".docx");
    const archetype = FILENAME_TO_ARCHETYPE[stem];
    if (!archetype) {
      console.warn(`  [SKIP] No archetype mapping for: ${file}`);
      continue;
    }

    const filePath = join(SOURCE_DIR, file);
    const result = await mammoth.convertToHtml({ path: filePath });

    if (result.messages.length > 0) {
      result.messages.forEach((m) => console.warn(`  [mammoth ${m.type}] ${file}: ${m.message}`));
    }

    const html = cleanHtml(result.value);
    entries.push([archetype, html]);
    console.log(`  ✓ ${archetype}`);
  }

  if (entries.length !== 14) {
    console.warn(`  WARNING: expected 14 archetypes, got ${entries.length}`);
  }

  const recordBody = entries
    .map(([name, html]) => {
      const escaped = html.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$/g, "\\$");
      return `  "${name}": \`${escaped}\``;
    })
    .join(",\n\n");

  const output = `// Auto-generated by scripts/convert-summary-docx.js — do not edit manually.
// Run: node scripts/convert-summary-docx.js

export const summaryArchetypeContent: Record<string, string> = {
${recordBody},
};
`;

  await writeFile(OUT_FILE, output, "utf8");
  console.log(`\nWrote ${entries.length} archetypes → data/report-summary.ts`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
